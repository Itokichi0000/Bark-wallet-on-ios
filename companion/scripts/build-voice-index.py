#!/usr/bin/env python3
"""Download recorded voice clips and write src/voice/voiceClips.ts.

usage: build-voice-index.py <lines.tsv> <results.jsonl>
  lines.tsv      key<TAB>text, the lines that were recorded (in recording order)
  results.jsonl  {"index": voice*1000 + textIndex, "url": ...} per finished clip
Clips are stored as small mono MP3s under assets/voice/<voice>/.
"""
import json, os, subprocess, sys, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VOICES = ["a", "b", "c"]

def main(lines_path, results_path):
    texts = []
    for line in open(lines_path, encoding="utf8").read().splitlines():
        _, text = line.split("\t", 1)
        if text not in texts:
            texts.append(text)
    clips = {v: {} for v in VOICES}
    seen = set()
    for row in open(results_path, encoding="utf8"):
        row = row.strip()
        if not row:
            continue
        r = json.loads(row)
        if r["index"] in seen or not r.get("url"):
            continue
        seen.add(r["index"])
        voice, i = VOICES[r["index"] // 1000], r["index"] % 1000
        out_dir = os.path.join(ROOT, "assets", "voice", voice)
        os.makedirs(out_dir, exist_ok=True)
        out = os.path.join(out_dir, f"{i:03d}.mp3")
        if not os.path.exists(out) or os.path.getsize(out) < 1000:
            raw = out + ".src"
            urllib.request.urlretrieve(r["url"], raw)
            subprocess.run(
                ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", "-i", raw,
                 "-af", "silenceremove=start_periods=1:start_threshold=-50dB,areverse,silenceremove=start_periods=1:start_threshold=-50dB,areverse,loudnorm=I=-18:TP=-1.5",
                 "-ac", "1", "-ar", "32000", "-b:a", "48k", out], check=True)
            os.remove(raw)
        clips[voice][texts[i]] = f"{voice}/{i:03d}.mp3"
    # Only lines recorded in every voice, and still in the app's catalogue, are offered.
    import re
    ja = open(os.path.join(ROOT, "src", "i18n", "ja.ts"), encoding="utf8").read()
    catalogue = {json.loads('"' + m + '"') for m in re.findall(r':\s*"((?:[^"\\]|\\.)*)"', ja)}
    common = [t for t in texts if all(t in clips[v] for v in VOICES) and t in catalogue]
    missing = {v: [i for i, t in enumerate(texts) if t not in clips[v]] for v in VOICES}
    with open(os.path.join(ROOT, "src", "voice", "voiceClips.ts"), "w", encoding="utf8") as f:
        f.write("// Generated by scripts/build-voice-index.py. Do not edit by hand.\n")
        f.write("// Maps a line of the fixed Japanese catalogue to its recorded clip, per voice.\n")
        f.write('export const VOICE_CLIPS: Record<"a" | "b" | "c", Record<string, number>> = {\n')
        for v in VOICES:
            f.write(f"  {v}: {{\n")
            for t in common:
                f.write(f"    {json.dumps(t, ensure_ascii=False)}: require(\"../../assets/voice/{clips[v][t]}\"),\n")
            f.write("  },\n")
        f.write("};\n")
    print(len(texts), "lines;", len(common), "in all voices; missing:", {v: len(m) for v, m in missing.items()})
    print(json.dumps(missing))

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
